using Chickensoft.Sync;
using Chickensoft.Sync.Primitives;
using Cubusky.BuildingBlocks;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Cubusky.Stats.Generators;

[Generator]
public sealed class StatGenerator : IIncrementalGenerator
{
    public static class TrackingName
    {
        public const string StatsToGenerate = nameof(StatsToGenerate);
    }

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<StatToGenerate> statsToGenerate = context
            .SyntaxProvider.ForAttributeWithMetadataName(
                StatToGenerate.StatAttributeFullName,
                predicate: static (node, _) =>
                {
                    return node is ClassDeclarationSyntax or RecordDeclarationSyntax { ClassOrStructKeyword.RawKind: not (int)SyntaxKind.StructKeyword };
                },
                transform: static (ctx, _) =>
                {
                    return new StatToGenerate((ctx.TargetSymbol as INamedTypeSymbol)!);
                }
            )
            .WithTrackingName(TrackingName.StatsToGenerate);

        context.RegisterSourceOutput(statsToGenerate, Execute);
    }

    private static void Execute(SourceProductionContext context, StatToGenerate statToGenerate)
    {
        const string Broadcaster = nameof(Stat<>.Broadcaster);
        const string Binding = nameof(Stat<>.Binding);

        var (@namespace, className, baseClassName) = statToGenerate;

        var iOperator = $"{nameof(IOperator<>)}<{className}>";
        var iOperation = $"{nameof(IOperation<>)}<{className}>";
        var iAutoObject = $"{nameof(IAutoObject<>)}<{className}.{Binding}>";
        var tOperation = $"T{nameof(IOperation<>)[1..]}";
        var whereTOperation = $"where {tOperation} : struct, {iOperation}";

        var source = $$"""
            // <auto-generated/>
            #nullable enable
            using {{nameof(Chickensoft)}}.{{nameof(Chickensoft.Sync)}};
            using {{nameof(Chickensoft)}}.{{nameof(Chickensoft.Sync)}}.{{nameof(Chickensoft.Sync.Primitives)}};
            using {{nameof(Cubusky)}}.{{nameof(BuildingBlocks)}};

            namespace {{@namespace}}
            {
                public partial interface I{{className}} : I{{baseClassName}}, {{iOperator}}, {{iAutoObject}}
                {
                    new void {{nameof(IOperator<>.Perform)}}<{{tOperation}}>(in {{tOperation}} operation)
                        {{whereTOperation}}
                    {
                        (({{iOperator}})this).{{nameof(IOperator<>.Perform)}}(in operation);
                    }

                    new {{className}}.{{Binding}} {{nameof(IAutoObject<>.Bind)}}();
                }

                public partial class {{className}} : I{{className}}, {{iOperator}}, {{iAutoObject}}
                {
                    void {{iOperator}}.{{nameof(IOperator<>.Perform)}}<{{tOperation}}>(in {{tOperation}} operation)
                    {
                        {{nameof(Stat<>.Perform)}}(this, operation, new {{Broadcaster}}({{nameof(Stat<>.Subject)}}));
                    }

                    public new {{Binding}} {{nameof(IAutoObject<>.Bind)}}() => new {{Binding}}({{nameof(Stat<>.Subject)}});

                    public new partial class {{Broadcaster}} : {{baseClassName}}.{{Broadcaster}}
                    {
                        protected internal {{Broadcaster}}({{nameof(SyncSubject)}} subject) : base(subject) { }
                    
                        public new void {{nameof(Stat<>.Broadcaster.Broadcast)}}<{{tOperation}}>(in {{tOperation}} operation)
                            {{whereTOperation}}
                        {
                            {{nameof(Stat<>.Broadcaster.Subject)}}.{{nameof(SyncSubject.Broadcast)}}(in operation);
                        }
                    }

                    public new partial class {{Binding}} : {{baseClassName}}.{{Binding}}
                    {
                        protected internal {{Binding}}({{nameof(ISyncSubject)}} subject) : base(subject) { }

                        public new {{Binding}} {{nameof(Stat<>.Binding.On)}}<{{tOperation}}>({{nameof(Callback<>)}}<{{tOperation}}> callback, {{nameof(Condition<>)}}<{{tOperation}}>? condition = null)
                            {{whereTOperation}}
                        {
                            AddCallback(callback, condition);
                            return this;
                        }
                    }
                }
            }
            """;

        context.AddSource($"{className.Replace('<', '{').Replace('>', '}')}.g.cs", source);
    }
}
